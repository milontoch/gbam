// Copies the support files that pdf.js loads on demand (decoders, fonts, character maps) from node_modules
// into public/pdfjs, so they are served from our own site. Runs automatically before "npm run build" and "npm run dev".
import fs from 'node:fs';
import path from 'node:path';

const from = 'node_modules/pdfjs-dist';
const to = 'public/pdfjs';

if (!fs.existsSync(from)) {
	console.error('pdfjs-dist is not installed. Run "npm install" first.');
	process.exit(1);
}
fs.rmSync(to, { recursive: true, force: true });
fs.mkdirSync(to, { recursive: true });
for (const dir of ['wasm', 'cmaps', 'standard_fonts', 'iccs']) fs.cpSync(path.join(from, dir), path.join(to, dir), { recursive: true });
fs.copyFileSync(path.join(from, 'LICENSE'), path.join(to, 'LICENSE'));
const version = JSON.parse(fs.readFileSync(path.join(from, 'package.json'), 'utf8')).version;
fs.writeFileSync(
	path.join(to, 'NOTICE.txt'),
	`These files come from pdf.js ${version} by Mozilla and contributors, licensed under the Apache License 2.0 (see LICENSE).\nhttps://github.com/mozilla/pdf.js\nThey are generated by scripts/copy-pdfjs-assets.mjs and are not stored in git.\n`,
);
console.log(`pdf.js ${version} support files copied to ${to}`);
